def inject_cmake_entries(operators, output_root: Path) -> int:
    """Append per-op `add_plugin(...)` entries to the Meos CMakeLists files
    (logical + physical layers). Idempotent: skips ops already listed."""
    n_added = 0
    for layer in ("logical", "physical"):
        parent = output_root / f"nes-{layer}-operators/src/Functions/Meos/CMakeLists.txt"
        if not parent.exists():
            sys.stderr.write(f"  ! cmake-entries: {parent} not found, skipping {layer} layer\n")
            continue
        layer_suffix = "Logical" if layer == "logical" else "Physical"
        # Group entries by target CMakeLists. Physical family operators go to a
        # per-family subdir CMakeLists gated by the matching option; logical
        # operators (and base physical) go to the flat parent. Idempotent.
        by_file = {}            # Path -> list[str]
        gated_families = set()  # family subdirs to ensure add_subdirectory() in parent
        for op in operators:
            # Family gating applies only to the physical layer (logical never
            # calls libmeos and is always compiled).
            fam = meos_family(op["nebula_name"]) if layer == "physical" else None
            if fam:
                cml = parent.parent / fam / "CMakeLists.txt"
                gated_families.add(fam)
            else:
                cml = parent
            entry = (
                f"add_plugin({op['nebula_name']} {layer_suffix}Function "
                f"nes-{layer}-operators {op['nebula_name']}{layer_suffix}Function.cpp)"
            )
            by_file.setdefault(cml, []).append(entry)
        for cml, entries in by_file.items():
            cml.parent.mkdir(parents=True, exist_ok=True)
            body = cml.read_text() if cml.exists() else (
                "# MEOS type-family operators, gated by the "
                f"{cml.parent.name.upper()} compile option.\n\n")
            new_lines = [e for e in entries
                         if f"add_plugin({e.split(' ',1)[0][len('add_plugin('):]} " not in body
                         and e not in body]
            if new_lines:
                with cml.open("a" if cml.exists() else "w") as f:
                    f.write(("" if cml.exists() else body) + "\n".join(new_lines) + "\n")
                n_added += len(new_lines)
        # Ensure the parent gates each new family subdir.
        pbody = parent.read_text()
        add = ""
        for fam in sorted(gated_families):
            if f"add_subdirectory({fam})" not in pbody:
                add += f"\nif({fam.upper()})\n    add_subdirectory({fam})\nendif()\n"
        if add:
            with parent.open("a") as f:
                f.write(add)
    return n_added


def inject_g4(operators, g4_path: Path) -> int:
    """Inject lexer-token + functionName-alternation entries into AntlrSQL.g4.
    Idempotent: skips tokens already present."""
    if not g4_path.exists():
        sys.stderr.write(f"  ! g4: {g4_path} not found, skipping\n")
        return 0
    body = g4_path.read_text()
    n_added = 0

    # 1) Lexer-token entries — insert just before the WATERMARK: lexer token.
    new_tokens = []
    for op in operators:
        tok = op["sql_token"]
        if re.search(rf"^{re.escape(tok)}\s*:", body, re.MULTILINE):
            continue
        new_tokens.append(
            f"{tok}: '{tok}' | '{tok.lower()}';"
        )
    if new_tokens:
        anchor_re = re.compile(r"^WATERMARK:.*$", re.MULTILINE)
        m = anchor_re.search(body)
        if m is None:
            sys.stderr.write(f"  ! g4: WATERMARK lexer anchor not found; cannot inject tokens\n")
        else:
            insertion = "/* BEGIN CODEGEN LEXER TOKENS */\n" + "\n".join(new_tokens) + "\n/* END CODEGEN LEXER TOKENS */\n"
            # If the BEGIN marker already exists, append inside that block; else insert before WATERMARK.
            if "/* BEGIN CODEGEN LEXER TOKENS */" in body:
                body = re.sub(
                    r"(/\* BEGIN CODEGEN LEXER TOKENS \*/\n)(.*?)(/\* END CODEGEN LEXER TOKENS \*/)",
                    lambda mm: mm.group(1) + mm.group(2) + "\n".join(new_tokens) + "\n" + mm.group(3),
                    body,
                    count=1,
                    flags=re.DOTALL,
                )
            else:
                body = body[: m.start()] + insertion + body[m.start():]
            n_added += len(new_tokens)
            sys.stderr.write(f"  ✓ g4 lexer-tokens: added {len(new_tokens)} token(s)\n")

    # 2) functionName: alternation — append missing tokens before the trailing ';'.
    fn_re = re.compile(r"^functionName:\s*([^;]+);", re.MULTILINE)
    m = fn_re.search(body)
    if m is None:
        sys.stderr.write(f"  ! g4: functionName production not found\n")
    else:
        alternation = m.group(1)
        new_alts = []
        for op in operators:
            tok = op["sql_token"]
            if re.search(rf"\b{re.escape(tok)}\b", alternation):
                continue
            new_alts.append(tok)
        if new_alts:
            new_alt_text = alternation.rstrip() + " | " + " | ".join(new_alts)
            body = body[: m.start()] + f"functionName:  {new_alt_text};" + body[m.end():]
            sys.stderr.write(f"  ✓ g4 functionName: added {len(new_alts)} alternative(s)\n")

    g4_path.write_text(body)
    return n_added


def _family_macro(name):
    """The -D<FAMILY> macro guarding a name's parser glue, or None for core types."""
    fam = meos_family(name)
    return fam.upper() if fam else None


def guard_parser_glue_by_family(body: str) -> str:
    """Wrap each family op's parser #include and dispatch glue block in
    `#if <FAMILY> ... #endif` so a `-D<FAMILY>=0` build omits the token entirely
    (the parser then has no case for it and rejects the function at plan time,
    matching MobilityDB/MEOS's -DCBUFFER=0 etc.). Idempotent + self-correcting:
    it strips any existing guard around a glue block/include and re-applies the
    right one, so re-runs and family reassignments converge."""
    fam_alt = "CBUFFER|NPOINT|POSE|RGEO"
    # 1) Dispatch glue blocks — both the function-op "PARSER GLUE" markers and the
    #    windowed-aggregation "AGGREGATION GLUE: TOKEN (variant)" markers (a token
    #    may have several variant blocks: case-switch / funcname-chain). The token
    #    is back-referenced so each BEGIN pairs with its own END.
    block_re = re.compile(
        rf"(?:#if (?:{fam_alt})\n)?"
        r"(/\* BEGIN CODEGEN GLUE: (\S+)(?: \([^)]*\))? \*/"
        r".*?"
        r"/\* END CODEGEN GLUE: \2(?: \([^)]*\))? \*/)"
        rf"(?:\n#endif /\* (?:{fam_alt}) \*/)?",
        re.DOTALL)
    def _wrap_block(m):
        block, token = m.group(1), m.group(2)
        macro = _family_macro(token)
        return f"#if {macro}\n{block}\n#endif /* {macro} */" if macro else block
    body = block_re.sub(_wrap_block, body)
    # 2) Per-op logical #includes — function-op (Functions/Meos/…LogicalFunction)
    #    and windowed-aggregation (Operators/Windows/Aggregations/Meos/…Aggregation
    #    LogicalFunction) headers alike.
    inc_re = re.compile(
        rf"(?:#if (?:{fam_alt})\n)?"
        r"(#include <(?:Functions/Meos/([A-Za-z0-9]+)LogicalFunction"
        r"|Operators/Windows/Aggregations/Meos/([A-Za-z0-9]+)AggregationLogicalFunction)\.hpp>)"
        rf"(?:\n#endif /\* (?:{fam_alt}) \*/)?")
    def _wrap_inc(m):
        inc, name = m.group(1), (m.group(2) or m.group(3))
        macro = _family_macro(name)
        return f"#if {macro}\n{inc}\n#endif /* {macro} */" if macro else inc
    return inc_re.sub(_wrap_inc, body)


def inject_parser_cpp(operators, cpp_path: Path) -> int:
    """Inject #include + dispatch-case block into AntlrSQLQueryPlanCreator.cpp.
    Idempotent: skips when the per-op BEGIN marker is already present."""
    if not cpp_path.exists():
        sys.stderr.write(f"  ! parser-cpp: {cpp_path} not found, skipping\n")
        return 0
    body = cpp_path.read_text()
    n_added = 0

    # 1) Per-op #include — append after the last existing Meos LogicalFunction include.
    new_includes = []
    for op in operators:
        inc = f"#include <Functions/Meos/{op['nebula_name']}LogicalFunction.hpp>"
        if inc in body:
            continue
        new_includes.append(inc)
    if new_includes:
        # Insert immediately after the last #include <Functions/Meos/...> line.
        meos_inc_re = re.compile(r"(^#include <Functions/Meos/[^>]+>\s*\n)+", re.MULTILINE)
        matches = list(meos_inc_re.finditer(body))
        if not matches:
            sys.stderr.write(f"  ! parser-cpp: could not find Meos include anchor\n")
        else:
            last = matches[-1]
            body = body[: last.end()] + "\n".join(new_includes) + "\n" + body[last.end():]
            sys.stderr.write(f"  ✓ parser-cpp includes: added {len(new_includes)}\n")

    # 2) Per-op dispatch cases — insert just before the `default:` of the
    #    switch that already contains the TGEO_AT_STBOX case.
    cases_block = []
    for op in operators:
        marker = f"/* BEGIN CODEGEN GLUE: {op['sql_token']} */"
        if marker in body:
            continue
        # Also skip if a pre-existing hand-written case for this token already
        # exists (no marker, but a `case AntlrSQLLexer::TOKEN:` line is present).
        if re.search(rf"case\s+AntlrSQLLexer::{re.escape(op['sql_token'])}\s*:", body):
            sys.stderr.write(
                f"  ! parser-cpp: pre-existing hand-written case for {op['sql_token']} detected; "
                f"skipping codegen injection (will not duplicate)\n"
            )
            continue
        if op.get("build_generic"):
            case_str = _generic_dispatch_case(op)          # arity baked in; final string
        else:
            tmpl = dispatch_case_for(op)
            if tmpl is None:
                sys.stderr.write(f"  ! parser-cpp: {op['nebula_name']} has no dispatch shape, skipping case\n")
                continue
            case_str = tmpl.format(sql_token=op["sql_token"], nebula_name=op["nebula_name"])
        cases_block.append(case_str)
        n_added += 1
    if cases_block:
        # Find the insertion point: prefer just after the LAST existing function-op
        # `/* END CODEGEN GLUE: TOKEN */` marker (so successive codegen runs cluster
        # their cases in the function-op case-switch), else fall back to inserting
        # before the `default:` that follows the TGEO_AT_STBOX case block.
        # NOTE the marker is unified across generators, so EXCLUDE the variant
        # markers ` (case-switch)` / ` (funcName chain)` (aggregation glue, a
        # different dispatch site) by forbidding '(' — else a function-op case would
        # land after an aggregation block (illegal switch jump).
        last_end_re = re.compile(r"/\* END CODEGEN GLUE: [^*(]+\*/")
        ends = list(last_end_re.finditer(body))
        if ends:
            insert_at = ends[-1].end()
            # If that marker sits inside a family `#if <FAMILY> … #endif` guard,
            # skip past the closing #endif so the new case lands at switch scope
            # (not nested in the guard — which would unbalance the #if/#endif). The
            # guard pass re-wraps each emitted block in its own #if as needed.
            m_endif = re.match(r"\s*\n#endif /\* (?:CBUFFER|NPOINT|POSE|RGEO) \*/", body[insert_at:])
            if m_endif:
                insert_at += m_endif.end()
            body = body[:insert_at] + "\n" + "\n".join(cases_block) + body[insert_at:]
            sys.stderr.write(f"  ✓ parser-cpp dispatch: added {len(cases_block)} case(s) after last codegen marker\n")
        else:
            anchor_re = re.compile(
                r"(case AntlrSQLLexer::TGEO_AT_STBOX:[\s\S]+?\n\s*break;\n)(\s*default:)",
            )
            m = anchor_re.search(body)
            if m is None:
                sys.stderr.write(f"  ! parser-cpp: no anchor (TGEO_AT_STBOX→default or codegen END marker) found\n")
            else:
                insertion = m.group(1) + "\n" + "\n".join(cases_block) + "\n" + m.group(2)
                body = body[: m.start()] + insertion + body[m.end():]
                sys.stderr.write(f"  ✓ parser-cpp dispatch: added {len(cases_block)} case(s) before default:\n")

    # Family-gate every per-op include + dispatch block so a -D<FAMILY>=0 build
    # drops the token (idempotent; covers both the just-injected and pre-existing
    # glue).
    body = guard_parser_glue_by_family(body)

    cpp_path.write_text(body)
    return n_added


# --- Regular-naming gate -----------------------------------------------------
# THE RULE: a Nebula SQL function token is exactly the genuine backing MEOS C
# symbol, uppercased  (token == meos_call.upper()).  This keeps the binding
# generatable straight from the MEOS-API catalog with no per-function naming
# decision, so a new MEOS function/type is a mechanical rollout (the minDistance
# and tbigint rollouts were the first hand-applications of this same idea).
# See tools/streaming_parity/naming_regularization.md.
NAMING_ALLOWLIST = {
    # BerlinMOD-benchmark helpers with no 1:1 MEOS symbol (documented exceptions).
    # TEMPORAL_LENGTH is the windowed trajectory-length aggregation (the per-event
    # tpoint_length is the regular TPOINT_LENGTH operator).
    "PAIR_MEETING", "TEMPORAL_SEQUENCE", "TEMPORAL_LENGTH", "CROSS_DISTANCE",
}


def enforce_regular_naming(operators):
    """Reject any operator whose SQL token is not its meos_call uppercased."""
    errs = []
    for op in operators:
        mc = op.get("meos_call")
        tok = op.get("sql_token")
        if not mc or tok in NAMING_ALLOWLIST:
            continue
        want = mc.upper()
        if tok != want:
            errs.append(f"  sql_token={tok!r} is irregular; "
                        f"meos_call={mc!r} requires sql_token={want!r}")
    if errs:
        sys.exit("ERROR: irregular SQL token(s) — a token MUST equal meos_call.upper() "
                 "(see tools/streaming_parity/naming_regularization.md):\n" + "\n".join(errs))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, help="Path to JSON descriptor file")
    parser.add_argument("--output-root", required=True, help="MobilityNebula repo root")
    parser.add_argument("--no-parser-glue", action="store_true",
                        help="Skip .g4 + parser .cpp injection (default: inject)")
    parser.add_argument("--no-cmake-entries", action="store_true",
                        help="Skip CMakeLists.txt injection (default: inject)")
    args = parser.parse_args()

    with open(args.input) as f:
        config = json.load(f)

    output_root = Path(args.output_root).resolve()
    if not (output_root / "nes-logical-operators").exists():
        sys.exit(f"ERROR: {output_root} does not look like a MobilityNebula root (no nes-logical-operators/)")

    operators = config["operators"]
    enforce_regular_naming(operators)
    sys.stderr.write(f"Emitting {len(operators)} operator(s):\n\n")
    for op in operators:
        emit_operator(op, output_root)

    if not args.no_cmake_entries:
        sys.stderr.write("\nCMakeLists.txt:\n")
        inject_cmake_entries(operators, output_root)

    if not args.no_parser_glue:
        sys.stderr.write("\nParser glue:\n")
        inject_g4(operators, output_root / "nes-sql-parser/AntlrSQL.g4")
        inject_parser_cpp(operators, output_root / "nes-sql-parser/src/AntlrSQLQueryPlanCreator.cpp")

    sys.stderr.write(
        f"\nDone. {len(operators) * 4} files emitted "
        f"(or 3 + .cpp-skipped for shapes without a physical-cpp template).\n"
    )


if __name__ == "__main__":
    main()
