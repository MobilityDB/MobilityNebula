def dispatch_case_for(op):
    """Pick the dispatch-case template that matches an operator's shape."""
    if op.get("build_two_temporal_points_with_dist"):
        return DISPATCH_CASE_TWO_TEMPORAL_POINTS_WITH_DIST
    if op.get("build_temporal_point_with_dist"):
        return DISPATCH_CASE_ONE_TEMPORAL_POINT_WITH_DIST
    if op.get("build_two_temporal_points"):
        return DISPATCH_CASE_TWO_TEMPORAL_POINTS
    if op.get("build_two_tpose_points_via_composition"):
        return DISPATCH_CASE_TWO_TPOSE_POINTS
    if op.get("build_tnpoint_point_via_composition"):
        # 4-arg SQL shape (rid, fraction, ts, geometry) — same arity as a
        # one-temporal-point op; the parser only pops/forwards by arity.
        return DISPATCH_CASE_ONE_TEMPORAL_POINT
    if op.get("build_two_tnpoint_points_via_composition"):
        # 6-arg SQL shape (ridA, fracA, tsA, ridB, fracB, tsB) — same arity
        # as a two-temporal-points op.
        return DISPATCH_CASE_TWO_TEMPORAL_POINTS
    # dwithin (W20): the with-dist composition shapes reuse existing with-dist
    # dispatches by arity + constant pattern (geometry+dist or dist-only lifted).
    if op.get("build_tpose_point_with_dist_via_composition"):
        # 6-arg: x, y, theta, ts (cols) + geometry, dist (constants) — same
        # shape as tcbuffer × geom + dist.
        return DISPATCH_CASE_TCBUFFER_POINT_WITH_DIST
    if op.get("build_two_tpose_points_with_dist_via_composition"):
        # 9-arg: 8 cols + dist constant — same shape as two-tcbuffer + dist.
        return DISPATCH_CASE_TWO_TCBUFFER_POINTS_WITH_DIST
    if op.get("build_tnpoint_point_with_dist_via_composition"):
        # 5-arg: rid, fraction, ts (cols) + geometry, dist (constants).
        return DISPATCH_CASE_ONE_TEMPORAL_POINT_WITH_DIST
    if op.get("build_two_tnpoint_points_with_dist_via_composition"):
        # 7-arg: 6 cols + dist constant.
        return DISPATCH_CASE_TWO_TEMPORAL_POINTS_WITH_DIST
    if op.get("build_temporal_point") or op.get("build_temporal_point_restriction"):
        # Both shapes share the same 4-arg dispatch (lon, lat, ts, geom);
        # only the physical-cpp body differs (filter-predicate int return vs.
        # restriction-survival int return).
        return DISPATCH_CASE_ONE_TEMPORAL_POINT
    if op.get("build_tcbuffer_point") or op.get("build_tcbuffer_point_cbuffer") \
       or op.get("build_tpose_point_via_composition"):
        # All three shapes share the same 5-arg dispatch (lon/x, lat/y, radius/theta, ts, blob);
        # only the physical-cpp body differs (blob parsed as GSERIALIZED vs Cbuffer; per-event
        # type construction is tcbuffer vs tpose with optional tpose_to_tpoint composition).
        return DISPATCH_CASE_TCBUFFER_POINT
    if op.get("build_two_tcbuffer_points"):
        return DISPATCH_CASE_TWO_TCBUFFER_POINTS
    if op.get("build_tcbuffer_point_with_dist") or op.get("build_tcbuffer_point_cbuffer_with_dist"):
        # Same 6-arg SQL dispatch for both — only physical-cpp body differs (blob parser).
        return DISPATCH_CASE_TCBUFFER_POINT_WITH_DIST
    if op.get("build_two_tcbuffer_points_with_dist"):
        return DISPATCH_CASE_TWO_TCBUFFER_POINTS_WITH_DIST
    if op.get("build_tnumber_point_with_scalar") or op.get("build_tnumber_scalar_first"):
        # scalar-first reuses the same 3-arg (value, ts, scalar) SQL dispatch;
        # only the physical-cpp body differs (MEOS call arg order).
        return DISPATCH_CASE_TNUMBER_POINT_WITH_SCALAR
    if op.get("build_two_tnumber_points"):
        return DISPATCH_CASE_TWO_TNUMBER_POINTS
    return None


def _generic_dispatch_case(op):
    """Parser dispatch case for a 'generic' operator. Arity is baked in (n =
    number of event fields); lifts string/number constants (geometry blobs,
    scalars) then pops n children in reverse and builds the LogicalFunction.
    Returns the final C++ string (no further .format)."""
    n = len(op["args"])
    tok, name = op["sql_token"], op["nebula_name"]
    pops = "\n".join(
        f"            auto a{i} = helpers.top().functionBuilder.back(); helpers.top().functionBuilder.pop_back();"
        for i in range(n - 1, -1, -1))
    ctor_args = ", ".join(f"a{i}" for i in range(n))
    return f"""        /* BEGIN CODEGEN GLUE: {tok} */
        case AntlrSQLLexer::{tok}:
        {{
            const auto argCount = context->expression().size();
            if (argCount != {n})
                throw InvalidQuerySyntax("{tok} requires exactly {n} arguments, but got {{}}", argCount);

            while (!helpers.top().constantBuilder.empty())
            {{
                auto constantValue = std::move(helpers.top().constantBuilder.back());
                helpers.top().constantBuilder.pop_back();
                DataType dataType;
                char* endPtr = nullptr;
                std::strtod(constantValue.c_str(), &endPtr);
                if (endPtr != nullptr && *endPtr == '\\0')
                    dataType = DataTypeProvider::provideDataType(DataType::Type::FLOAT64);
                else
                    dataType = DataTypeProvider::provideDataType(DataType::Type::VARSIZED);
                helpers.top().functionBuilder.emplace_back(ConstantValueLogicalFunction(dataType, std::move(constantValue)));
            }}

{pops}

            helpers.top().functionBuilder.emplace_back({name}LogicalFunction({ctor_args}));
        }}
        break;
        /* END CODEGEN GLUE: {tok} */
"""


