def build_ctor_args(args, type_fn):
    return ",\n                                          ".join(
        f"{type_fn(a)} {a['name']}" for a in args
    )


def build_pushes_logical(args):
    return "\n".join(f"    parameters.push_back(std::move({a['name']}));" for a in args)


def build_pushes_physical(args):
    return "\n".join(
        f"    parameterFunctions.push_back(std::move({a['name']}Function));" for a in args
    )


def build_registrar_pushes_logical(args, nebula_name):
    pushes = []
    for i, _ in enumerate(args):
        pushes.append(f"    auto arg{i} = std::move(arguments.children[{i}]);")
    pushes.append(
        f"    return {nebula_name}LogicalFunction(" + ", ".join(f"std::move(arg{i})" for i in range(len(args))) + ");"
    )
    return "\n".join(pushes)


def build_registrar_pushes_physical(args, nebula_name):
    pushes = []
    for i, _ in enumerate(args):
        # PhysicalFunctionRegistryArguments uses `childFunctions`, not `children`
        # (LogicalFunctionRegistryArguments uses `children` — see registry headers).
        pushes.append(f"    auto arg{i} = std::move(arguments.childFunctions[{i}]);")
    pushes.append(
        f"    return {nebula_name}PhysicalFunction(" + ", ".join(f"std::move(arg{i})" for i in range(len(args))) + ");"
    )
    return "\n".join(pushes)


def generic_fields(op):
    """The ordered (name, cpp) event fields for a 'generic' operator:
    the input type's fields followed by one per extra arg."""
    fields = list(GENERIC_INPUTS[op["input_type"]]["fields"])
    for i, ex in enumerate(op.get("extra_args", [])):
        if ex["kind"] == "temporal2":
            # a second temporal operand expands to its own per-event columns,
            # not a single arg field (must match assemble_generic_varsized_output).
            fields.extend(ex["t2_fields"])
        else:
            fields.append((f"arg{i}", ex["cpp"] if ex["kind"] == "scalar" else "VariableSizedData"))
    return fields


def meos_family(nebula_name):
    """The toggleable MEOS type family of an operator, or None for base types.
    Mirrors MobilityDB/MEOS's CBUFFER/NPOINT/POSE/RGEO compile options: a family
    operator's physical TU is gated by the matching CMake option."""
    s = nebula_name.lower()
    if "trgeo" in s or "rgeometry" in s:
        return "Rgeo"
    if "pose" in s:
        return "Pose"
    if "npoint" in s or "nsegment" in s:
        return "Npoint"
    if "cbuffer" in s:
        return "Cbuffer"
    return None


def emit_operator(op, output_root: Path):
    nebula_name = op["nebula_name"]
    if op.get("build_generic"):
        # Derive the canonical arg list + return metadata so the shared logical
        # and physical-hpp templates match the assembled physical .cpp.
        op["args"] = [{"name": n, "nautilus_type": c, "cpp_type": c} for n, c in generic_fields(op)]
        rt, nr = GENERIC_RETURNS[op["return_kind"]][:2]
        op.setdefault("return_type", rt)
        op.setdefault("nautilus_return", nr)
    n_args = len(op["args"])

    # Logical .hpp constructor args (LogicalFunction type each)
    ctor_logical_args = build_ctor_args(op["args"], cpp_logical_type)
    # Physical .hpp / .cpp constructor args use 'XxxFunction' naming convention
    physical_args = [{"name": a["name"] + "Function"} for a in op["args"]]
    ctor_physical_args = ",\n                                                          ".join(
        f"PhysicalFunction {a['name']}" for a in physical_args
    )

    ctor_logical_pushes = build_pushes_logical(op["args"])
    ctor_physical_pushes = build_pushes_physical(op["args"])
    registrar_l = build_registrar_pushes_logical(op["args"], nebula_name)
    registrar_p = build_registrar_pushes_physical(op["args"], nebula_name)

    common = {
        "nebula_name": nebula_name,
        "comment_one_liner": op["comment_one_liner"],
        "meos_call": op["meos_call"],
        "n_args": n_args,
        "nautilus_return": op["nautilus_return"],
        "return_type": op["return_type"],
        "ctor_logical_args": ctor_logical_args,
        "ctor_physical_args": ctor_physical_args,
        "ctor_logical_pushes": ctor_logical_pushes,
        "ctor_physical_pushes": ctor_physical_pushes,
        "registrar_pushes": registrar_l,
        # tnumber-shape extras (only consumed by the two tnumber templates).
        # tnumber_wkt_format is a fmt::format pattern that ends up in C++ as-is;
        # Python single-pass .format() means we want raw `{}@{}` here (no doubling).
        "tnumber_value_cpp_type": op.get("tnumber_value_cpp_type", "double"),
        "scalar_cpp_type":        op.get("scalar_cpp_type", "double"),
        "tnumber_wkt_format":     op.get("tnumber_wkt_format", "{}@{}"),
        "tnumber_in_fn":          op.get("tnumber_in_fn", "tfloat_in"),
    }

    # MEOS type-family: physical operators of a toggleable family live in a
    # per-family subdir (Cbuffer/Npoint/Pose/Rgeo) whose compilation is gated by
    # the matching CMake option, so a family OFF drops them and links cleanly
