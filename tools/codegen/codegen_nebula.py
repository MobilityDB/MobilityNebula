def assemble_generic_physical(op):
    """Build the physical .cpp for a 'generic' (build_generic) operator."""
    name = op["nebula_name"]
    if op["return_kind"] == "wkb":
        return assemble_wkb_output(op)
    if (op["return_kind"] in VARSIZED_OUT_RETURNS or op["return_kind"] in VALUE_OUT_RETURNS
            or op["return_kind"] in ("self_out", "temporal_wkb")
            or op.get("array_out") or op.get("array_in_round")):
        return assemble_generic_varsized_output(op)
    inp = GENERIC_INPUTS[op["input_type"]]
    ret_cpp, _, zero, extract_fn = GENERIC_RETURNS[op["return_kind"]]
    extras = op.get("extra_args", [])

    # Ordered (lambda-param) fields: primary input fields, then each extra arg's.
    fields = list(inp["fields"])
    headers = {"meos.h", inp["header"]}
    # op-level extra headers (e.g. meos_npoint.h / meos_pose.h for a meos_call
    # whose type lives outside meos.h/meos_geo.h).
    for h in op.get("extra_headers", []):
        headers.add(h)
    call_terms = ["temp"]
    parse_lines = []
    box_frees = []      # raw box/span literals to free after the MEOS call
    # An extra-arg parse failure must free the primary ONLY when it is a heap
    # pointer; a base-scalar primary (frees: False) is a plain value, so emit no
    # free(temp) in the failure paths (free(int) would not compile).
    ff = "free(temp); " if inp.get("frees", True) else ""
    for i, ex in enumerate(extras):
        if ex["kind"] == "scalar":
            fields.append((f"arg{i}", ex["cpp"]))
            call_terms.append(f"arg{i}")
        elif ex["kind"] == "scalar_text":
            # a scalar VALUE parsed from a quoted text field via a typed parser
            # (date_in -> DateADT, timestamptz_in -> TimestampTz). The parser
            # returns a plain value, so there is nothing to free.
            fields.append((f"arg{i}", "VariableSizedData"))
            headers.add(ex.get("header", "meos.h"))
            parse_lines.append(
                f'                std::string arg{i}S(arg{i}Ptr, arg{i}Size);\n'
                f'                while (!arg{i}S.empty() && (arg{i}S.front()==\'\\\'\' || arg{i}S.front()==\'"\')) arg{i}S.erase(arg{i}S.begin());\n'
                f'                while (!arg{i}S.empty() && (arg{i}S.back()==\'\\\'\' || arg{i}S.back()==\'"\')) arg{i}S.pop_back();\n'
                f'                {ex["ctype"]} arg{i}V = {ex["parser"]}(arg{i}S.c_str(){ex.get("parser_extra", "")});\n')
            call_terms.append(f"arg{i}V")
        elif ex["kind"] == "geom":
            fields.append((f"arg{i}", "VariableSizedData"))
            headers.add("meos_geo.h")
            parse_lines.append(
                f'                std::string arg{i}S(arg{i}Ptr, arg{i}Size);\n'
                f'                while (!arg{i}S.empty() && (arg{i}S.front()==\'\\\'\' || arg{i}S.front()==\'"\')) arg{i}S.erase(arg{i}S.begin());\n'
                f'                while (!arg{i}S.empty() && (arg{i}S.back()==\'\\\'\' || arg{i}S.back()==\'"\')) arg{i}S.pop_back();\n'
                f'                MEOS::Meos::StaticGeometry arg{i}G(arg{i}S);\n'
                f'                if (!arg{i}G.getGeometry()) {{ {ff}return {zero}; }}\n')
            call_terms.append(f"arg{i}G.getGeometry()")
        elif ex["kind"] == "box":
            # query-literal STBox/TBox/Span parsed from a text constant; freed
            # after the call. parser = stbox_in / tbox_in / tstzspan_in; box_type
            # = STBox / TBox / Span.
            fields.append((f"arg{i}", "VariableSizedData"))
            headers.add(ex.get("header", "meos.h"))
            parse_lines.append(
                f'                std::string arg{i}S(arg{i}Ptr, arg{i}Size);\n'
                f'                while (!arg{i}S.empty() && (arg{i}S.front()==\'\\\'\' || arg{i}S.front()==\'"\')) arg{i}S.erase(arg{i}S.begin());\n'
                f'                while (!arg{i}S.empty() && (arg{i}S.back()==\'\\\'\' || arg{i}S.back()==\'"\')) arg{i}S.pop_back();\n'
                f'                {ex["box_type"]}* arg{i}B = {ex["parser"]}(arg{i}S.c_str(){ex.get("parser_extra", "")});\n'
                f'                if (!arg{i}B) {{ {ff}return {zero}; }}\n')
            call_terms.append(f"arg{i}B")
            box_frees.append(f"free(arg{i}B);")
        elif ex["kind"] == "text":
            fields.append((f"arg{i}", "VariableSizedData"))
            parse_lines.append(
                f'                std::string arg{i}S(arg{i}Ptr, arg{i}Size);\n'
                f'                while (!arg{i}S.empty() && (arg{i}S.front()==\'\\\'\' || arg{i}S.front()==\'"\')) arg{i}S.erase(arg{i}S.begin());\n'
                f'                while (!arg{i}S.empty() && (arg{i}S.back()==\'\\\'\' || arg{i}S.back()==\'"\')) arg{i}S.pop_back();\n'
                f'                text* arg{i}T = text_in(arg{i}S.c_str());\n'
                f'                if (!arg{i}T) {{ {ff}return {zero}; }}\n')
            call_terms.append(f"arg{i}T")
            box_frees.append(f"free(arg{i}T);")
        elif ex["kind"] == "wkb_temporal":
            # a SECOND temporal operand carried as a VARSIZED hex-WKB field (e.g.
            # another per-vehicle aggregate output) — parsed via temporal_from_hexwkb,
            # freed after the call. For cross-vehicle f(trajA, trajB).
            fields.append((f"arg{i}", "VariableSizedData"))
            headers.add("meos_geo.h")
